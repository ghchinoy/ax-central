export function icon(
  name: IconName,
  size = 14,
  opts?: { color?: string; className?: string; strokeWidth?: number },
): TemplateResult {
  const sw = opts?.strokeWidth ?? 2;
  const cls = opts?.className ?? "";
  const style = opts?.color ? `color:${opts.color};flex:none` : "flex:none";
  return html`<svg
    class=${cls}
    width=${size}
    height=${size}
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    stroke-width=${sw}
    stroke-linecap="round"
    stroke-linejoin="round"
    style=${style}
    aria-hidden="true"
  >
    ${pathsFor(name)}
  </svg>`;
}

const PHASE_ICON_MAP: Record<string, IconName> = {
  pending: "hourglass",
  running: "circle-play",
  suspended: "circle-pause",
  completed: "circle-check",
  failed: "octagon-x",
  terminating: "trash",
};

export function renderPhaseIcon(phase: Phase, size = 14): TemplateResult {
  const name = PHASE_ICON_MAP[phase] ?? "circle-help";
  return icon(name, size, { color: phaseColor(phase), strokeWidth: 2.2 });
}

/** State is always icon + label, never color alone. */
export function renderPhaseBadge(phase: Phase): TemplateResult {
  return html`<span class="badge" style="--c:${phaseColor(phase)}">
    ${renderPhaseIcon(phase, 12)} ${phaseLabel(phase)}
  </span>`;
}

